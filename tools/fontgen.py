def trace(rows):
    """Return closed contours (lists of (x,y) in pixel units, y-up, baseline=0)."""
    h = len(rows)
    filled = set()
    for r, line in enumerate(rows):
        for c, ch in enumerate(line):
            if ch == '#':
                # convert to y-up: row 6 sits on baseline -> pixel spans y 0..1
                y = 6 - r
                filled.add((c, y))
    # directed edges, clockwise around each filled cell (in y-up, clockwise = TrueType outer)
    edges = {}
    def add(a, b):
        if (b, a) in edges:
            del edges[(b, a)]
        else:
            edges[(a, b)] = True
    for (x, y) in filled:
        # clockwise in y-up: (x,y)->(x,y+1)->(x+1,y+1)->(x+1,y)->(x,y)
        add((x, y), (x, y + 1))
        add((x, y + 1), (x + 1, y + 1))
        add((x + 1, y + 1), (x + 1, y))
        add((x + 1, y), (x, y))
    out = {}
    for (a, b) in edges:
        out.setdefault(a, []).append(b)
    contours = []
    used = set()
    for start_edge in list(edges.keys()):
        if start_edge in used:
            continue
        a, b = start_edge
        loop = [a]
        used.add(start_edge)
        prev, cur = a, b
        while cur != a:
            loop.append(cur)
            nexts = [n for n in out[cur] if (cur, n) not in used]
            if len(nexts) > 1:
                # prefer turning right (keeps diagonal-touching cells separate)
                dx, dy = cur[0] - prev[0], cur[1] - prev[1]
                right = (dy, -dx)
                nexts.sort(key=lambda n: 0 if (n[0] - cur[0], n[1] - cur[1]) == right else 1)
            n = nexts[0]
            used.add((cur, n))
            prev, cur = cur, n
        # drop collinear points
        simp = []
        L = len(loop)
        for i in range(L):
            p0, p1, p2 = loop[i - 1], loop[i], loop[(i + 1) % L]
            if (p1[0] - p0[0]) * (p2[1] - p1[1]) - (p1[1] - p0[1]) * (p2[0] - p1[0]) != 0:
                simp.append(p1)
        contours.append(simp)
    return contours


def build(out_dir):
    names = {}
    order = ['.notdef', 'space']
    cmap = {32: 'space'}
    for ch in G:
        n = 'uni%04X' % ord(ch)
        names[ch] = n
        order.append(n)
        cmap[ord(ch)] = n
    fb = FontBuilder(UPM, isTTF=True)
    fb.setupGlyphOrder(order)
    fb.setupCharacterMap(cmap)
    glyphs, metrics = {}, {}
    pen = TTGlyphPen(None)
    pen.moveTo((0, 0)); pen.lineTo((0, 700)); pen.lineTo((400, 700)); pen.lineTo((400, 0)); pen.closePath()
    glyphs['.notdef'] = pen.glyph(); metrics['.notdef'] = (500, 0)
    glyphs['space'] = TTGlyphPen(None).glyph(); metrics['space'] = (400, 0)
    for ch, rows in G.items():
        pen = TTGlyphPen(None)
        for c in trace(rows):
            pen.moveTo((c[0][0] * PX, c[0][1] * PX))
            for p in c[1:]:
                pen.lineTo((p[0] * PX, p[1] * PX))
            pen.closePath()
        w = max(len(r) for r in rows)
        glyphs[names[ch]] = pen.glyph()
        metrics[names[ch]] = ((w + 1) * PX, 0)
    fb.setupGlyf(glyphs)
    fb.setupHorizontalMetrics(metrics)
    fb.setupHorizontalHeader(ascent=ASC, descent=-DESC)
    fb.setupNameTable({'familyName': 'Lowtown', 'styleName': 'Regular',
                         'uniqueFontIdentifier': 'Lowtown-Regular', 'fullName': 'Lowtown',
                         'psName': 'Lowtown-Regular', 'version': 'Version 1.0'})
    fb.setupOS2(sTypoAscender=ASC, sTypoDescender=-DESC, sTypoLineGap=0,
                usWinAscent=ASC, usWinDescent=DESC, sxHeight=500, sCapHeight=700)
    fb.setupPost()
    path = os.path.join(out_dir, 'lowtown.ttf')
    fb.save(path)
    b64 = base64.b64encode(open(path, 'rb').read()).decode()
    css = "@font-face{font-family:'Lowtown';src:url(data:font/ttf;base64,%s) format('truetype');font-display:block}\n" % b64
    open(os.path.join(out_dir, 'font.css'), 'w').write(css)
    print('glyphs', len(G), 'ttf bytes', os.path.getsize(path))


if __name__ == '__main__':
    build(sys.argv[1] if len(sys.argv) > 1 else '.')
