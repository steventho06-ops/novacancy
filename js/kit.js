  // text on a plane. dir: 'x' (faces +z) or 'z' (faces +x). px = size of one font pixel.
  // o: { emit, depth, mat, colFn(i) }
  function text(mb, str, x, y, z, px, col, o = {}) {
    str = String(str).toUpperCase();
    const n = str.length, w = n * 6 - 1, dir = o.dir || 'x', dp = o.depth || px * 0.6;
    const left = o.align === 'left' ? 0 : o.align === 'right' ? -w * px : -w * px / 2;
    for (let ci = 0; ci < n; ci++) {
      const g = F[str[ci]] || F[' '];
      const c = o.colFn ? o.colFn(ci) : col;
      for (let r = 0; r < 7; r++) for (let k = 0; k < 5; k++) {
        if (g[r][k] !== '1') continue;
        const u = left + (ci * 6 + k) * px + px / 2, v = y + (6 - r) * px;
        if (dir === 'x') mb.box(x + u, v, z, px * 1.02, px * 1.02, dp, c, { emit: o.emit || 0, mat: o.mat || 0, jit: 0 });
        else mb.box(x, v, z - u, dp, px * 1.02, px * 1.02, c, { emit: o.emit || 0, mat: o.mat || 0, jit: 0 });
      }
    }
    return w * px;
  }
  const textWidth = (str, px) => (String(str).length * 6 - 1) * px;

  // neon tube outline rectangle on a plane (dir 'x' faces +z)
